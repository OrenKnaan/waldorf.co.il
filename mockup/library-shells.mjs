// Moves each work's text out of its static page and into D1, leaving the page a
// shell that asks the content API for it.
//
//   node mockup/library-pages.mjs          # full pages, text baked in
//   node mockup/patch-old-site-links.mjs   # rewrites their old-site links
//   node mockup/library-shells.mjs         # this: text -> SQL, pages -> shells
//   cd content-api && npx wrangler@4 d1 execute waldorf-content --remote --file seed/library-pages.sql
//   node mockup/search-index.mjs           # reads the text back from the API
//
// Why: a static file on GitHub Pages is public whatever D1 says, so freezing or
// binning a work in the admin hid it from the library list and left its whole
// text one URL away (and in search-index.json). Served from the Worker, the
// text goes only to a visitor while the work is published, or to an admin or a
// preview pass whatever its status. See GET /api/content/library/:id/page.
//
// The shell keeps the site chrome and the URL, so every link and every old-site
// redirect that points at lib-<id>.html still lands. What it no longer carries is
// anything about the work: not the text, not the title, not the breadcrumb JSON-LD
// that named it. library.js fills <main> in, and breadcrumb.js waits for it.
//
// Safe to re-run: a page that is already a shell (data-lib-pending) is skipped,
// so its row in the SQL is left out rather than overwritten with a shell.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(root, 'pages');
const sqlPath = join(root, '..', 'content-api', 'seed', 'library-pages.sql');

// D1 refuses a statement over 100,000 bytes and the longest work is three times
// that, so each text goes in as an UPDATE that empties the column followed by
// appends that stay under the limit.
const CHUNK_BYTES = 80000;
const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;
function chunks(text) {
  const out = [];
  let cur = '', bytes = 0;
  for (const ch of text) {
    const b = Buffer.byteLength(ch);
    if (bytes + b > CHUNK_BYTES) { out.push(cur); cur = ''; bytes = 0; }
    cur += ch; bytes += b;
  }
  if (cur) out.push(cur);
  return out;
}

const SHELL = (src) => `<main id="main-content" tabindex="-1" data-lib-item="${src}" data-lib-pending>
  <nav class="pagebanner" aria-label="breadcrumb">
    <span class="crumbs">
<a class="crumb" href="./home.html">דף הבית</a>
<span class="crumb-sep" aria-hidden="true">/</span>
<a class="crumb" href="./content-library.html">ספריית תוכן</a>
</span>
  </nav>
  <p class="lib-loading" role="status">טוען את הפריט…</p>
  <noscript><p>כדי לקרוא את הפריט יש להפעיל JavaScript בדפדפן.</p></noscript>
</main>`;

const sql = [
  '-- Generated by mockup/library-shells.mjs. The full text of each work, served',
  '-- by GET /api/content/library/:id/page. Do not edit by hand; re-run the script.',
];
let shelled = 0, skipped = 0;
for (const file of readdirSync(pagesDir).filter((f) => /^lib-.*\.html$/.test(f)).sort()) {
  const path = join(pagesDir, file);
  let html = readFileSync(path, 'utf8');
  const m = html.match(/<main id="main-content"[^>]*data-lib-item="([^"]+)"[^>]*>([\s\S]*?)<\/main>/);
  if (!m) { console.warn(`${file}: no library <main>, left alone`); continue; }
  if (/data-lib-pending/.test(m[0])) { skipped += 1; continue; }
  const src = m[1];
  const id = `lb-${src}`;
  const parts = chunks(m[2].trim());
  sql.push(`UPDATE library SET page_html = ${sqlString(parts[0])} WHERE id = ${sqlString(id)};`);
  for (const p of parts.slice(1)) sql.push(`UPDATE library SET page_html = page_html || ${sqlString(p)} WHERE id = ${sqlString(id)};`);

  html = html.replace(m[0], SHELL(src));
  // The title and the JSON-LD named the work; a hidden one must not be named.
  html = html.replace(/<title>[^<]*<\/title>/, '<title>ספריית תוכן — מוקאפ</title>');
  html = html.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/, '');
  writeFileSync(path, html, 'utf8');
  shelled += 1;
}

if (shelled) {
  mkdirSync(dirname(sqlPath), { recursive: true });
  writeFileSync(sqlPath, sql.join('\n') + '\n', 'utf8');
  console.log(`${shelled} page(s) turned into shells; their text is in ${sqlPath}.`);
  console.log('Load it: cd content-api && npx wrangler@4 d1 execute waldorf-content --remote --file seed/library-pages.sql');
}
if (skipped) console.log(`${skipped} page(s) were already shells.`);
