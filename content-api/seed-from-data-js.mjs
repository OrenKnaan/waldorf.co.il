// Turns the mockup's hardcoded seed (mockup/pages/data.js) into SQL for D1.
//
//   node content-api/seed-from-data-js.mjs > content-api/migrations/0002_seed.sql
//
// One-time-ish: re-running regenerates the same file, and the SQL uses
// INSERT OR REPLACE so applying it twice is harmless. Once the content lives in
// D1 this script is history — it exists to get the data across, not to stay in
// the loop. data.js keeps its records only so this stays reproducible; nothing
// reads it at runtime any more.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'mockup/pages/data.js'), 'utf8');
const sandbox = { window: {} };
new Function('window', src)(sandbox.window);
const SEED = sandbox.window.WALDORF_DATA;

const q = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null || v === '' || Number.isNaN(Number(v)) ? 'NULL' : Number(v));
const b = (v) => (v ? 1 : 0);
const NOW = 'strftime(\'%s\',\'now\')';

// collection -> [table, columns, row -> values]. Column order matches the schema.
const MAP = {
  events: ['events', 'id,title,date,time,location,description,register_url,status,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.date), q(r.time), q(r.location), q(r.description), q(r.registerUrl), q(r.status || 'draft'), b(r.demo), i]],
  news: ['news', 'id,title,date,section,summary,link,status,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.date), q(r.section), q(r.summary), q(r.link), q(r.status || 'draft'), b(r.demo), i]],
  board: ['board', 'id,title,category,description,region,contact,date,status,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.category), q(r.description), q(r.region), q(r.contact), q(r.date), q(r.status || 'pending'), b(r.demo), i]],
  jobs: ['jobs', 'id,role,institution,category,region,scope,contact,description,date,status,demo,position',
    (r, i) => [q(r.id), q(r.role), q(r.institution), q(r.category), q(r.region), q(r.scope), q(r.contact), q(r.description), q(r.date), q(r.status || 'pending'), b(r.demo), i]],
  library: ['library', 'id,title,kind,description,url,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.kind), q(r.description), q(r.url), b(r.demo), i]],
  teaching: ['teaching', 'id,title,grp,url,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.group), q(r.url), b(r.demo), i]],
  forms: ['forms', 'id,title,category,description,url,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.category), q(r.description), q(r.url), b(r.demo), i]],
  mapPoints: ['map_points', 'id,name,town,count,lat,lng,url,demo,position',
    (r, i) => [q(r.id), q(r.name), q(r.town), n(r.count ?? 1), n(r.lat), n(r.lng), q(r.url), b(r.demo), i]],
  videos: ['videos', 'id,title,youtube_id,description,demo,position',
    (r, i) => [q(r.id), q(r.title), q(r.youtubeId), q(r.description), b(r.demo), i]],
  podcast: ['podcast', 'id,title,num,date,duration,description,url,demo,position',
    (r, i) => [q(r.id), q(r.title), n(r.num), q(r.date), q(r.duration), q(r.description), q(r.url), b(r.demo), i]],
};

const out = ['-- Generated by content-api/seed-from-data-js.mjs — do not hand-edit.', ''];
let total = 0;

for (const [col, [table, cols, row]] of Object.entries(MAP)) {
  const items = SEED[col] || [];
  if (!items.length) continue;
  out.push(`-- ${col} -> ${table} (${items.length})`);
  items.forEach((r, i) => {
    out.push(`INSERT OR REPLACE INTO ${table} (${cols},created_at,updated_at) VALUES (${row(r, i).join(',')},${NOW},${NOW});`);
    total += 1;
  });
  out.push('');
}

if (SEED.about) {
  out.push('-- about -> singletons');
  out.push(`INSERT OR REPLACE INTO singletons (key,value,updated_at) VALUES ('about',${q(JSON.stringify(SEED.about))},${NOW});`);
  total += 1;
}

console.log(out.join('\n'));
process.stderr.write(`${total} rows across ${Object.keys(MAP).length} tables\n`);
