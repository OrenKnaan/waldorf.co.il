// Turns migration/url-map.csv into a Cloudflare Pages `_redirects` file.
//
//   node migration/build-redirects.mjs            > preview on stdout
//   node migration/build-redirects.mjs --write    > writes public/_redirects
//
// No network, no dependencies: the CSV is the reviewed artefact and this only
// reformats it. Re-run it whenever the table changes.
//
// Two things it deliberately does NOT handle, because `_redirects` cannot:
//
//   1. www.waldorf.co.il -> waldorf.co.il. Host canonicalisation is a Redirect
//      Rule in the Cloudflare dashboard (or a Bulk Redirect list), applied to
//      the zone rather than to the Pages project.
//   2. Anything under /wp-admin/, /wp-content/, /wp-json/ or /feed/. Those are
//      WordPress internals with no counterpart; let them 404 rather than
//      pointing them somewhere misleading.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

// Minimal CSV reader: enough for this file, which is generated rather than
// hand-typed, so the only quoting it ever contains is around commas in titles.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const rows = parseCsv(readFileSync(join(here, 'url-map.csv'), 'utf8'));

// The old slugs are Hebrew, and a browser sends them percent-encoded. Match on
// the encoded form so the rule fires on the request as it actually arrives.
// encodeURI leaves the slashes alone, which is what a path needs.
const encode = (p) => encodeURI(p);

const seen = new Set();
const lines = [];
let skipped = 0;

for (const r of rows) {
  if (!r.new_path) { skipped += 1; continue; }
  const from = encode(r.old_path);
  if (seen.has(from)) continue;
  seen.add(from);
  lines.push(`${from} ${r.new_path} 301`);
  // WordPress serves these with a trailing slash and the sitemap lists them
  // that way, but inbound links in the wild drop it. One extra rule each is
  // cheaper than losing the redirect.
  if (from.endsWith('/') && from !== '/') {
    const bare = from.slice(0, -1);
    if (!seen.has(bare)) { seen.add(bare); lines.push(`${bare} ${r.new_path} 301`); }
  }
}

const header = [
  '# Generated by migration/build-redirects.mjs from migration/url-map.csv.',
  '# Do not hand-edit: edit the CSV and re-run.',
  `# ${rows.length} mapped URLs from the old WordPress site, ${lines.length} rules.`,
  '#',
  '# Cloudflare Pages allows 2,100 static rules; this is well inside that.',
  '# Host canonicalisation (www -> apex) is a zone Redirect Rule, not this file.',
  '',
].join('\n');

const out = header + lines.join('\n') + '\n';

if (process.argv.includes('--write')) {
  mkdirSync(join(root, 'public'), { recursive: true });
  writeFileSync(join(root, 'public', '_redirects'), out, 'utf8');
  console.log(`public/_redirects: ${lines.length} rules from ${rows.length} mapped URLs.`);
  if (skipped) console.log(`${skipped} row(s) had no target and were skipped.`);
} else {
  process.stdout.write(out);
  console.error(`\n(${lines.length} rules; pass --write to save to public/_redirects)`);
}
